#!/usr/bin/env python3
"""bin2h.py NAME IN.bin OUT.h: a binary as a C array NAME[] and NAME_size."""
import sys
from pathlib import Path


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    name, src, dst = sys.argv[1], Path(sys.argv[2]), Path(sys.argv[3])
    data = src.read_bytes()
    lines = [f"/* Generated by tools/bin2h.py from {src.name}. */",
             f"static const unsigned char {name}[] __attribute__((aligned(4))) = {{"]
    for i in range(0, len(data), 16):
        lines.append("  " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
    lines.append("};")
    lines.append(f"#define {name}_size {len(data)}u")
    dst.write_text("\n".join(lines) + "\n", encoding="ascii", newline="\n")


if __name__ == "__main__":
    main()
